// Seeded PRNG so a run is fully reproducible from its seed: the bag shuffle,
// and later the shop and reward rolls, all draw from one deterministic stream.
// mulberry32 is a small, well-distributed 32-bit generator adequate for a game,
// never for anything security-bearing.

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Fisher-Yates over a copy, driven by the supplied stream so the same seed
// yields the same order.
export function shuffle(arr, rng) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
